const SocialLinkCard = ({ link }) => {
  const getIcon = () => {
    switch (link.type) {
      case 'linkedin':
        return <LinkedInIcon />;
      case 'behance':
        return <BehanceIcon />;
      case 'instagram':
        return <InstagramIcon />;
      case 'figma':
        return <FigmaIcon />;
      default:
        return link.icon ? <img src={link.icon} alt="" className="w-10 h-10 rounded-lg" /> : <LinkIcon />;
    }
  };

  const cardClasses = `
    group relative bg-white rounded-2xl overflow-hidden shadow-sm hover:shadow-md 
    transition-all duration-300 hover:-translate-y-0.5
    ${link.type === 'behance' ? 'row-span-2' : ''}
  `;

  // Behance layout - vertical with full height
  if (link.type === 'behance') {
    return (
      <a 
        href={link.url} 
        target="_blank" 
        rel="noopener noreferrer"
        className={cardClasses}
      >
        <div className="p-5 h-full flex flex-col">
          {/* Header - Side by Side Layout */}
          <div className="flex items-center gap-4">
            {/* Icon and Text */}
            <div className="flex items-center gap-3 flex-1 min-w-0">
              <div className="flex-shrink-0">
                {getIcon()}
              </div>
              <div className="flex-1 min-w-0">
                <div className="font-semibold text-gray-900 truncate text-base">
                  {link.title}
                </div>
                <div className="text-sm text-gray-500 truncate">
                  {link.host}
                </div>
              </div>
            </div>
            
            {/* Follow Button */}
            {link.followers && (
              <div className="flex-shrink-0">
                <button className="px-4 py-1.5 bg-blue-600 text-white rounded-full text-sm font-medium hover:bg-blue-700 transition-colors">
                  Follow <span className="ml-1">{link.followers}</span>
                </button>
              </div>
            )}
          </div>

          {/* Grid for Behance - Below header */}
          {link.grid && (
            <div className="mt-4 grid grid-cols-3 gap-2 flex-1">
              {link.grid.map((img, idx) => (
                <div key={idx} className="aspect-square rounded-lg overflow-hidden">
                  <img 
                    src={img} 
                    alt=""
                    className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300"
                  />
                </div>
              ))}
            </div>
          )}
        </div>
      </a>
    );
  }

  // LinkedIn and Instagram layout - horizontal with image on right
  return (
    <a 
      href={link.url} 
      target="_blank" 
      rel="noopener noreferrer"
      className={cardClasses}
    >
      <div className="p-5 flex items-center gap-4">
        {/* Left side - Icon, Title, and Follow button */}
        <div className="flex flex-col gap-3 flex-1 min-w-0">
          <div className="flex items-center gap-3">
            <div className="flex-shrink-0">
              {getIcon()}
            </div>
            <div className="flex-1 min-w-0">
              <div className="font-semibold text-gray-900 truncate text-base">
                {link.title}
              </div>
              <div className="text-sm text-gray-500 truncate">
                {link.host}
              </div>
            </div>
          </div>
          
          {/* Follow Button */}
          {link.followers && (
            <div className="self-start">
              <button className="px-4 py-1.5 bg-blue-600 text-white rounded-full text-sm font-medium hover:bg-blue-700 transition-colors">
                Follow <span className="ml-1">{link.followers}</span>
              </button>
            </div>
          )}
        </div>

        {/* Right side - Image or Grid */}
        {link.image && !link.grid && (
          <div className="flex-shrink-0 w-36 h-24 rounded-xl overflow-hidden">
            <img 
              src={link.image} 
              alt={link.title}
              className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300"
            />
          </div>
        )}

        {link.grid && (
          <div className="flex-shrink-0 grid grid-cols-2 gap-1.5 w-36">
            {link.grid.slice(0, 4).map((img, idx) => (
              <div key={idx} className="aspect-square rounded-lg overflow-hidden">
                <img 
                  src={img} 
                  alt=""
                  className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300"
                />
              </div>
            ))}
          </div>
        )}
      </div>
    </a>
  );
};

export default SocialLinkCard;